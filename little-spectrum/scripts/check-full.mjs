#!/usr/bin/env node
// Complete pre-push verification: fast checks, production build, database and policy tests,
// then browser journeys against the production build. Every step must pass, nothing is skipped.
import { spawn } from "node:child_process";
import { readFileSync } from "node:fs";
import { setTimeout as sleep } from "node:timers/promises";

const PORT = Number(process.env.CHECK_PORT ?? 3100);
const results = [];

function loadEnvLocal() {
  try {
    for (const line of readFileSync(".env.local", "utf8").split("\n")) {
      const match = line.match(/^([A-Z0-9_]+)=(.*)$/);
      if (match && process.env[match[1]] === undefined) process.env[match[1]] = match[2];
    }
  } catch {}
}

function run(name, command, args, options = {}) {
  return new Promise((resolve) => {
    const started = Date.now();
    console.log(`\n▶ ${name}`);
    const child = spawn(command, args, { stdio: "inherit", shell: process.platform === "win32", ...options });
    child.on("exit", (code) => {
      const ok = code === 0;
      results.push({ name, ok, seconds: Math.round((Date.now() - started) / 1000) });
      console.log(`${ok ? "✓" : "✗"} ${name} (${Math.round((Date.now() - started) / 1000)}s)`);
      resolve(ok);
    });
  });
}

function assertLocalBackend() {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL ?? "";
  const local = /^https?:\/\/(127\.0\.0\.1|localhost|supabase_kong_[a-z0-9_-]+|host\.docker\.internal)(:\d+)?/i.test(url);
  if (!url) throw new Error("NEXT_PUBLIC_SUPABASE_URL is not set. Start the local stack with `pnpm supabase start` and fill .env.local.");
  if (!local && process.env.ALLOW_REMOTE_TEST_DB !== "1") {
    throw new Error(`Refusing to run database tests against ${url}. Point .env.local at a local Supabase, or set ALLOW_REMOTE_TEST_DB=1 for a disposable project you own.`);
  }
}

async function waitForBackend() {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  for (let i = 0; i < 30; i += 1) {
    try {
      const res = await fetch(`${url}/auth/v1/health`, { headers: { apikey: process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY ?? process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY ?? "" } });
      if (res.ok) return;
    } catch {}
    await sleep(1000);
  }
  throw new Error(`Supabase at ${url} did not answer /auth/v1/health. Is \`pnpm supabase start\` running?`);
}

async function waitForServer(url) {
  for (let i = 0; i < 60; i += 1) {
    try {
      const res = await fetch(url);
      if (res.status < 500) return;
    } catch {}
    await sleep(500);
  }
  throw new Error(`Server at ${url} did not become ready`);
}

let server = null;
function stopServer() {
  if (server && !server.killed) {
    server.kill("SIGTERM");
    server = null;
  }
}
process.on("exit", stopServer);
process.on("SIGINT", () => {
  stopServer();
  process.exit(130);
});

loadEnvLocal();
// Links generated by the build must point at the server under test.
process.env.NEXT_PUBLIC_SITE_URL = `http://localhost:${PORT}`;
let failed = false;
try {
  if (!(await run("Fast checks (typecheck, lint, unit)", "pnpm", ["check"]))) failed = true;
  if (!(await run("Production build", "pnpm", ["build"]))) failed = true;
  assertLocalBackend();
  await waitForBackend();
  if (!(await run("Database and policy tests", "pnpm", ["test:db"]))) failed = true;
  if (!failed) {
    console.log(`\n▶ Starting production server on port ${PORT}`);
    server = spawn("pnpm", ["exec", "next", "start", "-p", String(PORT)], { stdio: ["ignore", "inherit", "inherit"] });
    await waitForServer(`http://localhost:${PORT}/welcome`);
    const ok = await run("Browser journeys against the build", "pnpm", ["exec", "playwright", "test"], {
      env: { ...process.env, E2E_BASE_URL: `http://localhost:${PORT}`, E2E_PROD: "1" },
    });
    if (!ok) failed = true;
    stopServer();
  } else {
    console.log("\nSkipping browser journeys because an earlier step failed. That counts as a failure.");
  }
} catch (error) {
  failed = true;
  console.error(`\n✗ ${error instanceof Error ? error.message : String(error)}`);
} finally {
  stopServer();
}

console.log("\nSummary");
for (const r of results) console.log(`  ${r.ok ? "✓" : "✗"} ${r.name} (${r.seconds}s)`);
if (failed) {
  console.log("\ncheck:full failed. Fix the failures above before pushing.");
  process.exit(1);
}
console.log("\ncheck:full passed.");
